package splitwise.balanceSheet;

public class Balance {
    double oweAmount;
    double getBackMoneyAmount;

    public double getOweAmount() {
        return oweAmount;
    }

    public void setOweAmount(double oweAmount) {
        this.oweAmount = oweAmount;
    }

    public double getGetBackMoneyAmount() {
        return getBackMoneyAmount;
    }

    public void setGetBackMoneyAmount(double getBackMoneyAmount) {
        this.getBackMoneyAmount = getBackMoneyAmount;
    }
}
